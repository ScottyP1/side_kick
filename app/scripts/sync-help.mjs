// Copies the public guides from docs/guide/ into the app (src/lib/help-content.ts) for the help center at /docs.
// Usage: npm --prefix app run help:sync            → rewrites src/lib/help-content.ts
//        node scripts/sync-help.mjs --check        → exits 1 if it's out of date (the tests run this)
//
// Why a copy: the Docker image and the Azure deploy build only the app/ folder, so the app can't read
// ../docs at build or run time. A generated module also means the help center serves a fixed list of guides
// by name, never a file path from the address bar (so /docs/../PROGRESS can't reach anything).
//
// Parts of a guide meant only for developers (test file names, how to change a rule) are wrapped in
// <!-- help-center:skip --> … <!-- /help-center:skip --> and left out of the copy; on GitHub they still show.
// Any other HTML comment is dropped too.
//
// Only the guides in PUBLIC_GUIDES are copied: written for customers, with nothing internal. The Owner
// Console guide (for the Sidekick operator: setup codes, kill switches, Azure secrets), the guide index and
// the developer docs (PROGRESS, ARCHITECTURE, HOSTING, RUNBOOKS, security reports) never are.
import fs from "node:fs";
import path from "node:path";

const APP = path.resolve(import.meta.dirname, "..");
const GUIDES = path.resolve(APP, "../docs/guide");
const OUT = path.join(APP, "src/lib/help-content.ts");

/** The guides published at /docs/<name>, in the order the help center lists them. */
const PUBLIC_GUIDES = ["concepts", "admin-guide", "teams-guide", "meetings", "roles-and-permissions", "connect-devops-jira", "install-app"];

/** A guide's Markdown as the help center shows it: developer-only parts and HTML comments removed. */
const publicText = (md) =>
  md
    .replace(/<!-- help-center:skip -->[\s\S]*?<!-- \/help-center:skip -->\n?/g, "")
    .replace(/<!--[\s\S]*?-->\n?/g, "")
    .replace(/\n{3,}/g, "\n\n");

const body = PUBLIC_GUIDES.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(publicText(fs.readFileSync(path.join(GUIDES, `${name}.md`), "utf8")))},`).join("\n");
const text = `/**
 * @file GENERATED by scripts/sync-help.mjs from docs/guide/*.md: don't edit by hand. Edit the guide in
 * docs/guide/ and run \`npm --prefix app run help:sync\` (a test fails while this copy is out of date).
 * The public guides' Markdown by name, in help-center order; read through lib/help.ts.
 */

/** Markdown of each public guide, keyed by its name (the file name in docs/guide/ without .md). */
export const GUIDE_MARKDOWN: Record<string, string> = {
${body}
};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("src/lib/help-content.ts is out of date with docs/guide/. Run: npm --prefix app run help:sync");
    process.exit(1);
  }
  console.log("Help center copy is up to date.");
} else {
  fs.writeFileSync(OUT, text);
  console.log(`Wrote ${path.relative(APP, OUT)} (${PUBLIC_GUIDES.length} guides).`);
}
